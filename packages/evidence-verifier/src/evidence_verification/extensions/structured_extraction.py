"""Pure, opt-in extraction representation; no source entailment or inference.

Callers supply their existing typed schema and immutable source catalogue. The
normalizer never decides clinical truth and retains rejected proposals verbatim.
"""
from copy import deepcopy
from collections import Counter

TASK_VERSION = 'clinical-structured-extraction/1'
NORMALIZATION_VERSION = 'clinical-structured-normalization/1'


def prompt_fragment():
    return ("\nSTRUCTURED EXTRACTION/1: Assign each fact a unique stable fact_id; relationships name those IDs, not array positions. "
        "Each fact expresses one independently asserted proposition; retain distinct plans, actual events, and explicit documentation statements. "
        "Keep attributes on their own proposition. Put elapsed duration only in semantics.duration, frequency in semantics.frequency, "
        "and dates, relative event times, life stages, or event delays in semantics.event_time; preserve the source wording. "
        "Choose polarity for the named proposition: a negative test result does not make the test absent; "
        "missing documentation does not establish an absent clinical event. One executed dose/session does not establish a completed course. "
        "Use assertion_basis for the actual assertion, including plans rather than observations of execution. "
        "Select primary_source_id from that fact's citations, or null; preserve all cited question/answer context. "
        "These are extracted proposals. Do not invent missing information or change values to satisfy downstream rules.")


def _node(shape, node):
    return shape['$defs'][node['$ref'].split('/')[-1]] if '$ref' in node else node


def build_schema(base_typed_schema, source_catalogue):
    """Derive one wire schema without changing the supplied historical schema."""
    shape = deepcopy(base_typed_schema)
    fact = _node(shape, shape['properties']['facts']['items'])
    semantics = _node(shape, fact['properties']['semantics'])
    attributes = shape['$defs']['Attributes']
    attributes['properties'].pop('duration')
    attributes['required'].remove('duration')
    semantics['properties'].pop('assertion_basis')
    semantics['required'].remove('assertion_basis')
    ids = [entry['source_id'] for entry in source_catalogue]
    if not ids or len(ids)!=len(set(ids)):
        raise ValueError('Source catalogue must contain unique source identities')
    shape['$defs']['References']['properties']['source_ids']['items']['enum']=ids
    fact['properties'].update(fact_id={'type':'string','minLength':1},
        primary_source_id={'anyOf':[{'type':'string','enum':ids},{'type':'null'}]})
    fact['required'].extend(['fact_id','primary_source_id'])
    relation = _node(shape, shape['properties']['relationships']['items'])
    for name in ('from_fact_index','to_fact_index'):
        relation['properties'].pop(name)
        relation['required'].remove(name)
    for name in ('from_fact_id','to_fact_id'):
        relation['properties'][name] = {'type':'string','minLength':1}
        relation['required'].append(name)
    return shape


def _validation_errors(value, node, shape, path):
    """Validate the bounded JSON-schema subset generated by the existing types."""
    node = _node(shape,node)
    if 'anyOf' in node:
        branches = [_validation_errors(value, branch, shape, path) for branch in node['anyOf']]
        return [] if any(not errors for errors in branches) else [path+': invalid union value']
    kind = node.get('type')
    valid = {'null': value is None, 'string': isinstance(value,str), 'integer': type(value) is int,
        'number': type(value) in (int,float), 'boolean': type(value) is bool,
        'object': isinstance(value,dict), 'array': isinstance(value,list)}
    if kind and not valid.get(kind,False):
        return [path+': expected '+kind]
    if 'const' in node and value != node['const']:
        return [path+': wrong constant']
    if 'enum' in node and value not in node['enum']:
        return [path+': value outside enum']
    errors=[]
    if isinstance(value,str) and len(value)<node.get('minLength',0):
        errors.append(path+': string too short')
    if type(value) in (int,float) and value<node.get('minimum',float('-inf')):
        errors.append(path+': below minimum')
    if isinstance(value,list):
        if len(value)<node.get('minItems',0):errors.append(path+': array too short')
        for index,item in enumerate(value):
            errors.extend(_validation_errors(item,node['items'],shape,f'{path}[{index}]'))
    if isinstance(value,dict):
        properties=node.get('properties',{})
        for name in node.get('required',[]):
            if name not in value:errors.append(path+'.'+name+': missing required field')
        for name,item in value.items():
            if name in properties:errors.extend(_validation_errors(item,properties[name],shape,path+'.'+name))
            elif node.get('additionalProperties') is False:errors.append(path+'.'+name+': unexpected field')
    return errors


def normalize(payload, source_catalogue, base_typed_schema):
    """Return legacy proposals plus lossless, separately consumable typed fields.

    ``payload`` has no semantics/IDs/anchor extensions, so a product can pass it
    through its existing fact/source resolver. ``semantic_proposals`` contains
    only mechanically valid fields; missing/invalid values remain in quarantine,
    never silently become a clinical unknown. All indices refer to this returned
    payload; ``accepted_original_indices`` maps them to the unchanged raw facts.
    """
    wire = build_schema(base_typed_schema,source_catalogue)
    if not isinstance(payload,dict) or set(payload)!={'document_id','facts','relationships'}:
        raise ValueError('Expected exactly document_id, facts, relationships')
    if (not isinstance(payload['facts'],list) or not isinstance(payload['relationships'],list)
            or _validation_errors(payload['document_id'],wire['properties']['document_id'],wire,'document_id')):
        raise ValueError('Malformed extraction identity or lists')
    fact_shape=_node(wire,wire['properties']['facts']['items'])
    semantic_shape=_node(wire,fact_shape['properties']['semantics'])
    attribute_shape=wire['$defs']['Attributes']
    relation_shape=_node(wire,wire['properties']['relationships']['items'])
    counts=Counter(f.get('fact_id') for f in payload['facts']
        if isinstance(f,dict) and isinstance(f.get('fact_id'),str))
    facts=[];accepted=[];semantics=[];anchors=[];fields=[];rejected=[];errors=[];mapping={}
    def quarantine(index,field,value,reasons,*,missing=False):
        fields.append({'original_fact_index':index,'field':field,'raw_value':deepcopy(value),
            'missing':missing,'errors':reasons,'status':'QUARANTINED_NOT_ADOPTED'})
        errors.extend(reasons)
    for index,original in enumerate(payload['facts']):
        main_shape=deepcopy(fact_shape)
        optional={'semantics','attributes','primary_source_id'}
        main_shape['properties']={k:v for k,v in main_shape['properties'].items() if k not in optional}
        main_shape['required']=[k for k in main_shape['required'] if k not in optional]
        main={k:v for k,v in original.items() if k not in optional} if isinstance(original,dict) else original
        reasons=_validation_errors(main,main_shape,wire,f'facts[{index}]')
        if isinstance(original,dict):
            identity=original.get('fact_id')
            if isinstance(identity,str) and counts[identity]!=1:reasons.append(f'facts[{index}].fact_id: duplicate identity')
            citations=original.get('evidence',{}).get('source_ids',[]) if isinstance(original.get('evidence'),dict) else []
            if all(isinstance(v,str) for v in citations) and len(citations)!=len(set(citations)):
                reasons.append(f'facts[{index}].evidence: duplicate source identity')
        if reasons:
            rejected.append({'original_index':index,'raw_fact':deepcopy(original),'errors':reasons})
            errors.extend(reasons);continue
        fact={k:deepcopy(v) for k,v in main.items() if k!='fact_id'}
        attrs=original.get('attributes')
        valid_attrs={name:None for name in ('severity','duration','value','unit')}
        if 'attributes' not in original:
            quarantine(index,'attributes',None,[f'facts[{index}].attributes: missing required field'],missing=True)
        elif attrs is not None and not isinstance(attrs,dict):
            quarantine(index,'attributes',attrs,[f'facts[{index}].attributes: expected object or null'])
        elif isinstance(attrs,dict):
            for name in sorted(set(attribute_shape['properties']) | set(attrs)):
                node=attribute_shape['properties'].get(name)
                reasons=([f'facts[{index}].attributes.{name}: unexpected field'] if node is None else
                    [f'facts[{index}].attributes.{name}: missing required field'] if name not in attrs else
                    _validation_errors(attrs[name],node,wire,f'facts[{index}].attributes.{name}'))
                if reasons:quarantine(index,'attributes.'+name,attrs.get(name),reasons,missing=name not in attrs)
                else:valid_attrs[name]=attrs[name]
        raw_semantics=original.get('semantics');valid_semantics={'assertion_basis':original['assertion_basis']};invalid=[]
        if not isinstance(raw_semantics,dict):
            invalid=list(semantic_shape['properties'])
            quarantine(index,'semantics',raw_semantics,[f'facts[{index}].semantics: expected object'],missing='semantics' not in original)
        else:
            for name in sorted(set(semantic_shape['properties']) | set(raw_semantics)):
                node=semantic_shape['properties'].get(name)
                reasons=([f'facts[{index}].semantics.{name}: unexpected field'] if node is None else
                    [f'facts[{index}].semantics.{name}: missing required field'] if name not in raw_semantics else
                    _validation_errors(raw_semantics[name],node,wire,f'facts[{index}].semantics.{name}'))
                if reasons:
                    # assertion_basis has one authoritative wire location on
                    # the fact. An unexpected duplicate is quarantined without
                    # invalidating the independently valid fact-level field.
                    if name not in valid_semantics:invalid.append(name)
                    quarantine(index,'semantics.'+name,raw_semantics.get(name),reasons,missing=name not in raw_semantics)
                else:valid_semantics[name]=deepcopy(raw_semantics[name])
        if 'duration' in valid_semantics:valid_attrs['duration']=valid_semantics['duration']
        fact['attributes']=valid_attrs if any(v is not None for v in valid_attrs.values()) else None
        primary=original.get('primary_source_id')
        reasons=([f'facts[{index}].primary_source_id: missing required field'] if 'primary_source_id' not in original else
            _validation_errors(primary,fact_shape['properties']['primary_source_id'],wire,f'facts[{index}].primary_source_id'))
        if not reasons and primary is not None and primary not in original['evidence']['source_ids']:
            reasons=[f'facts[{index}].primary_source_id: not among this fact citations']
        if reasons:quarantine(index,'primary_source_id',primary,reasons,missing='primary_source_id' not in original);primary=None
        selected=deepcopy(original['evidence']['source_ids'])
        adopted=([primary]+[identity for identity in selected if identity!=primary]) if primary is not None else selected[:]
        fact['evidence']['source_ids']=adopted
        normalized_index=len(facts);mapping[original['fact_id']]=normalized_index
        facts.append(fact);accepted.append(index)
        semantics.append({'fact_index':normalized_index,'semantics':valid_semantics,'invalid_fields':sorted(invalid)})
        anchors.append({'fact_index':normalized_index,'wire_fact_id':original['fact_id'],
            'primary_source_id':primary,'selected_source_ids':selected,'adopted_source_ids':adopted})
    relations=[];quarantined=[]
    for index,original in enumerate(payload['relationships']):
        reasons=_validation_errors(original,relation_shape,wire,f'relationships[{index}]')
        if not reasons and any(original[name] not in mapping for name in ('from_fact_id','to_fact_id')):
            reasons=[f'relationships[{index}]: unknown or rejected fact identity']
        if reasons:
            errors.extend(reasons);quarantined.append({'original_index':index,'raw_relationship':deepcopy(original),
                'errors':reasons,'status':'QUARANTINED_NOT_ADOPTED','endpoint_repair_attempted':False})
        else:relations.append({'from_fact_index':mapping[original['from_fact_id']],
            'to_fact_index':mapping[original['to_fact_id']],'relation':original['relation'],'evidence':deepcopy(original['evidence'])})
    return {'version':NORMALIZATION_VERSION,'payload':{'document_id':payload['document_id'],'facts':facts,'relationships':relations},
        'primary_reference_application':'model-selected-primary/1',
        'accepted_original_indices':accepted,'semantic_proposals':semantics,'anchors':anchors,
        'field_quarantine':fields,'rejected_facts':rejected,'errors':errors,
        'relationship_quarantine':{'version':'relationship-quarantine/1','items':quarantined,
            'raw_relationship_count':len(payload['relationships']),'accepted_relationship_count':len(relations)},
        'interpretation':'MODEL_EXTRACTED_PROPOSALS_NOT_SOURCE_VERIFIED'}


def preserving_repair(original, replacement, source_catalogue, base_typed_schema):
    """Permit only repairs to previously invalid fields or relationship IDs."""
    before=normalize(original,source_catalogue,base_typed_schema)
    after=normalize(replacement,source_catalogue,base_typed_schema)
    if (len(original['facts'])!=len(replacement['facts'])
            or len(original['relationships'])!=len(replacement['relationships'])):
        raise ValueError('Mechanical repair changed proposal count')
    def identical(left,right):
        import json
        return json.dumps(left,sort_keys=True)==json.dumps(right,sort_keys=True)
    invalid={}
    for record in before['field_quarantine']:
        invalid.setdefault(record['original_fact_index'],set()).add(record['field'])
    for index in before['accepted_original_indices']:
        left=deepcopy(original['facts'][index]);right=deepcopy(replacement['facts'][index])
        for path in invalid.get(index,[]):
            parts=path.split('.')
            if len(parts)==1:
                left.pop(parts[0],None);right.pop(parts[0],None)
            elif isinstance(left.get(parts[0]),dict) and isinstance(right.get(parts[0]),dict):
                left[parts[0]].pop(parts[1],None);right[parts[0]].pop(parts[1],None)
        if not identical(left,right) or index not in after['accepted_original_indices']:
            raise ValueError('Mechanical repair changed valid fact content')
    rejected_relations={r['original_index'] for r in before['relationship_quarantine']['items']}
    for index,left in enumerate(original['relationships']):
        right=replacement['relationships'][index]
        if index in rejected_relations and isinstance(left,dict) and isinstance(right,dict):
            left={k:v for k,v in left.items() if k not in {'from_fact_id','to_fact_id'}}
            right={k:v for k,v in right.items() if k not in {'from_fact_id','to_fact_id'}}
        if not identical(left,right):
            raise ValueError('Mechanical repair changed valid relationship content')
    return after
